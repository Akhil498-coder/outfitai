-- Users for email/password and Google sign-in (kept as separate account types).
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(100),                 -- null for GOOGLE accounts
    auth_provider VARCHAR(20)  NOT NULL,        -- LOCAL or GOOGLE
    google_sub    VARCHAR(100) UNIQUE,          -- Google's stable user id, null for LOCAL
    display_name  VARCHAR(100) NOT NULL,
    age           INTEGER,
    gender        VARCHAR(30),
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
